// Copy bookkit's AI-usage policies (policies/*.md in the bookkit repo) into the
// website as src/lib/bookkit-policies.ts, so a book's `ai_policy` means exactly
// the same thing on bookkit.net as in a terminal.
//
//   node scripts/sync-bookkit-policies.mjs [path/to/bookkit]
//
// Default bookkit path: ../../writing/bookkit (or $BOOKKIT_DIR).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { parse } from "yaml";

const dir = resolve(process.argv[2] ?? process.env.BOOKKIT_DIR ?? join(import.meta.dirname, "../../../writing/bookkit"), "policies");
const MARKER = "<!-- bookkit:block -->";
const policies = readdirSync(dir).filter(f => f.endsWith(".md") && f !== "README.md").sort().map(file => {
  const text = readFileSync(join(dir, file), "utf8");
  const m = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) throw new Error(`${file}: missing front matter`);
  const meta = parse(m[1]);
  const name = file.replace(/\.md$/, "");
  if (meta.policy !== name) throw new Error(`${file}: front matter names ${meta.policy}`);
  const rest = text.slice(m[0].length);
  if (!rest.includes(MARKER)) throw new Error(`${file}: no ${MARKER}`);
  const [body, block] = [rest.slice(0, rest.indexOf(MARKER)), rest.slice(rest.indexOf(MARKER) + MARKER.length)];
  return { name, version: meta.version, summary: String(meta.summary).trim(), manuscriptWrites: meta.manuscript_writes, body: body.trim(), block: block.trim() };
});
const out = `// Generated by scripts/sync-bookkit-policies.mjs from bookkit/policies. Do not edit.
// Change a policy in the bookkit repo, raise its version, and run the script again.
export interface BookkitPolicy { name: string; version: number; summary: string; manuscriptWrites: "forbidden" | "assisted" | "permitted"; body: string; block: string }
export const BOOKKIT_POLICIES: BookkitPolicy[] = ${JSON.stringify(policies, null, 2)};
`;
writeFileSync(join(import.meta.dirname, "../src/lib/bookkit-policies.ts"), out);
console.log(`Wrote ${policies.length} policies: ${policies.map(p => `${p.name} v${p.version}`).join(", ")}`);
